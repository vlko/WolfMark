namespace WolfMark.Sync.ClaudeCode.Tests;

/// <summary>Synthetic transcript lines modelled on several Claude Code versions.</summary>
internal static class Samples
{
    public const string Session = "4f1c2d3e-0000-4000-8000-000000000001";

    public static string User(string uuid, string timestamp, string content, string extra = "", string session = Session, string cwd = "/work/WolfMark") =>
        $$"""{"parentUuid":null,"isSidechain":false,"userType":"external","cwd":"{{cwd}}","sessionId":"{{session}}","version":"2.1.0","gitBranch":"main","type":"user","message":{"role":"user","content":{{content}}},"uuid":"{{uuid}}","timestamp":"{{timestamp}}"{{extra}}}""";

    public static string Text(string text) => System.Text.Json.JsonSerializer.Serialize(text, SampleJson.Default.String);

    public static readonly string[] MixedTranscript =
    [
        // Plain string prompt (current format)
        User("u1", "2026-10-15T12:03:00.000Z", Text("Refaktoruj indexer")),
        // Assistant + tool use – ignored
        """{"type":"assistant","message":{"role":"assistant","content":[{"type":"tool_use","id":"t1","name":"Read","input":{}}]},"uuid":"a1","timestamp":"2026-10-15T12:03:05.000Z","sessionId":"4f1c2d3e-0000-4000-8000-000000000001"}""",
        // Tool result in a user turn – ignored
        User("u2", "2026-10-15T12:03:06.000Z", """[{"type":"tool_result","tool_use_id":"t1","content":"file"}]"""),
        // Meta message injected by the CLI – ignored
        User("u3", "2026-10-15T12:03:07.000Z", Text("Caveat: The messages below were generated by the user while running local commands."), ""","isMeta":true"""),
        // Subagent (sidechain) prompt – ignored
        User("u4", "2026-10-15T12:04:00.000Z", Text("Search the codebase for X"), "").Replace("\"isSidechain\":false", "\"isSidechain\":true"),
        // Older format: content as array of text parts, no gitBranch
        """{"type":"user","sessionId":"4f1c2d3e-0000-4000-8000-000000000001","cwd":"/work/WolfMark","message":{"role":"user","content":[{"type":"text","text":"Pridaj testy"},{"type":"image","source":{}}]},"uuid":"u5","timestamp":"2026-10-15T12:10:00Z"}""",
        // Corrupted line – skipped
        """{"type":"user","message":{"role":"user","content":"broken""",
        // Slash command
        User("u6", "2026-10-15T12:20:00.000Z", Text("<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>PR 42</command-args>")),
        // Command output – ignored
        User("u7", "2026-10-15T12:20:01.000Z", Text("<local-command-stdout>done</local-command-stdout>")),
        // Bash mode input
        User("u8", "2026-10-15T12:21:00.000Z", Text("<bash-input>git status</bash-input>")),
        // Compaction summary – ignored
        User("u9", "2026-10-15T12:30:00.000Z", Text("This session is being continued from a previous conversation that ran out of context."), ""","isCompactSummary":true"""),
        // Interrupt marker – ignored
        User("u10", "2026-10-15T12:31:00.000Z", """[{"type":"text","text":"[Request interrupted by user]"}]"""),
        // Unknown future fields are fine
        User("u11", "2026-10-15T12:40:00.000Z", Text("Over AOT build"), ""","futureField":{"x":[1,2,3]},"promptSource":"typed" """.TrimEnd()),
        // Unknown record types
        """{"type":"file-history-snapshot","snapshot":{}}""",
        """{"type":"ai-title","title":"x"}""",
        string.Empty,
    ];
}

