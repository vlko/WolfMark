using Microsoft.UI.Xaml.Controls;
using WolfMark.Editor;

namespace WolfMark.App.Theming;

/// <summary>One icon per editor command – shared by the toolbar above the editor and its context menu.</summary>
internal static class FormatIcons
{
    /// <summary>Toolbar icon (the toolbar button sizes itself to the content).</summary>
    public static FontIcon Create(EditorCommand command, double size = 14) => Build(command, size, size + 1, 0);

    /// <summary>
    /// Menu icon. Menu items size icons in a fixed 16×16 slot made for icon fonts; text glyphs (H1, ¶, 1.)
    /// would land small in the top-left corner, so those come as vector outlines of the same font
    /// (<see cref="FormatIconPaths"/>, generated by tools/gen-icon-paths.py).
    /// </summary>
    public static IconElement CreateForMenu(EditorCommand command) =>
        FormatIconPaths.Paths.TryGetValue(command, out var path) ? PathIcons.Create(path) : Build(command, 16, 16, 0);

    private static FontIcon Build(EditorCommand command, double glyphSize, double textSize, double textNudge) => command switch
    {
        EditorCommand.Heading1 => Text("H1", textSize, textNudge),
        EditorCommand.Heading2 => Text("H2", textSize, textNudge),
        EditorCommand.Heading3 => Text("H3", textSize, textNudge),
        EditorCommand.Paragraph => Text("¶", textSize + 1, textNudge),
        EditorCommand.Quote => Text("“", textSize + 5, textNudge + 3),
        EditorCommand.NumberedList => Text("1.", textSize, textNudge),
        EditorCommand.Strikethrough => Text("S\u0336", textSize + 1, textNudge),
        EditorCommand.BulletList => Glyph("\uE8FD", glyphSize),
        EditorCommand.Bold => Glyph(Glyphs.Bold, glyphSize),
        EditorCommand.Italic => Glyph(Glyphs.Italic, glyphSize),
        EditorCommand.Code => Glyph(Glyphs.Code, glyphSize),
        EditorCommand.Link => Glyph(Glyphs.Link, glyphSize),
        EditorCommand.Task => Glyph(Glyphs.CheckboxComposite, glyphSize),
        _ => Glyph(Glyphs.Edit, glyphSize),
    };

    private static FontIcon Glyph(string glyph, double size) => new() { Glyph = glyph, FontFamily = Typo.Icons, FontSize = size };

    /// <summary>Text "icons" (H1, ¶, 1.) in the condensed face used by the headers.</summary>
    private static FontIcon Text(string text, double size, double nudge) => new()
    {
        Glyph = text,
        FontFamily = Typo.CondensedBold,
        FontSize = size,
        Margin = new Microsoft.UI.Xaml.Thickness(0, nudge, 0, 0),
    };
}
